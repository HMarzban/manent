const DESTRUCTIVE_COMMANDS: ReadonlySet<string> = new Set([
  "doc.moveToTrash",
  "app.signOut",
  "rundown.deleteRows",
  "production.end",
]);

/** The Lucide icon associated with a registered command id, or null when unmapped. */
export function commandIconFor(id: string): LucideIcon | null {
  return COMMAND_ICONS[id] ?? null;
}

/** The Lucide icon associated with a CommandMenu submenu label, or null when unmapped. */
export function submenuIconFor(label: string): LucideIcon | null {
  return SUBMENU_ICONS[label] ?? null;
}

/** Whether a menu command represents a destructive or session-ending action. */
export function isDestructiveCommand(id: string): boolean {
  return DESTRUCTIVE_COMMANDS.has(id);
}

/** Renders the leading menu icon for a command id (or null when unmapped). */
export function CommandMenuIcon(props: { readonly id: string }): ReactNode {
  const Icon = commandIconFor(props.id);
  if (Icon === null) return null;
  return <Icon aria-hidden="true" className="size-icon shrink-0" />;
}
