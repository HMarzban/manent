import { expect, test } from "bun:test";
import {
  ACK_TIMEOUT_MS,
  BACKOFF_BASE_MS,
  BACKOFF_CAP_MS,
  BATCH_BYTES,
  BATCH_ENTRIES,
  ConnectError,
  DEVICE_VERSION_INTERVAL_MS,
  FLUSH_FALLBACK_MS,
  HANDSHAKE_TIMEOUT_MS,
  HEARTBEAT_MS,
  IN_FLIGHT,
  LOCAL_CHECKPOINT_EVERY,
  PONG_TIMEOUT_MS,
  PROBE_TIMEOUT_MS,
  RESTART_SPREAD_MS,
  RETRY_NOW_JITTER_MS,
  STABLE_AFTER_MS,
  SUBSCRIBE_CLIENT_IDS,
  StoreError,
  TAB_PROTOCOL_VERSION,
  WELCOME_TIMEOUT_MS,
} from "../src/index.ts";

test("the client's numbers are the agreed ones", () => {
  expect({
    BACKOFF_BASE_MS,
    BACKOFF_CAP_MS,
    STABLE_AFTER_MS,
    RESTART_SPREAD_MS,
    RETRY_NOW_JITTER_MS,
    HEARTBEAT_MS,
    PONG_TIMEOUT_MS,
    PROBE_TIMEOUT_MS,
    WELCOME_TIMEOUT_MS,
    HANDSHAKE_TIMEOUT_MS,
    ACK_TIMEOUT_MS,
    FLUSH_FALLBACK_MS,
    BATCH_BYTES,
    BATCH_ENTRIES,
    IN_FLIGHT,
    LOCAL_CHECKPOINT_EVERY,
    DEVICE_VERSION_INTERVAL_MS,
    SUBSCRIBE_CLIENT_IDS,
    TAB_PROTOCOL_VERSION,
  }).toEqual({
    BACKOFF_BASE_MS: 500,
    BACKOFF_CAP_MS: 30_000,
    STABLE_AFTER_MS: 10_000,
    RESTART_SPREAD_MS: 5_000,
    RETRY_NOW_JITTER_MS: 1_000,
    HEARTBEAT_MS: 15_000,
    PONG_TIMEOUT_MS: 10_000,
    PROBE_TIMEOUT_MS: 1_500,
    WELCOME_TIMEOUT_MS: 10_000,
    HANDSHAKE_TIMEOUT_MS: 10_000,
    ACK_TIMEOUT_MS: 30_000,
    FLUSH_FALLBACK_MS: 50,
    BATCH_BYTES: 1_048_576,
    BATCH_ENTRIES: 1024,
    IN_FLIGHT: 8,
    LOCAL_CHECKPOINT_EVERY: 500,
    DEVICE_VERSION_INTERVAL_MS: 3_600_000,
    SUBSCRIBE_CLIENT_IDS: 256,
    TAB_PROTOCOL_VERSION: 1,
  });
  expect([
    new ConnectError("sign_in").code,
    new StoreError("quota").code,
    new StoreError("quota") instanceof Error,
  ]).toEqual(["sign_in", "quota", true]);
});
