const TABLES = "packages/pagination/src/engines/v1/tables";
const V3_TABLES = "packages/pagination/src/engines/v3/tables";
const HEADER =
  "// Generated by tools/unicode/generate-tables.ts. Do not edit.\n";
const PER_LINE = 100;

/** Grapheme_Cluster_Break values in table order: a value's class is its index plus 1, and 0 is Other. */
const GCB_CLASSES = [
  "CR",
  "LF",
  "Control",
  "Extend",
  "ZWJ",
  "Regional_Indicator",
  "Prepend",
  "SpacingMark",
  "L",
  "V",
  "T",
  "LV",
  "LVT",
] as const;

/** The fields of each data line, comments and blank lines left out. */
function dataLines(text: string): string[][] {
  return text
    .split("\n")
    .map((line) => line.split("#")[0]!.trim())
    .filter((line) => line !== "")
    .map((line) => line.split(";").map((field) => field.trim()));
}

function codeRange(field: string): [number, number] {
  const [from, to] = field.split("..").map((hex) => parseInt(hex, 16));
  return [from!, to ?? from!];
}

function codePoints(field: string): string {
  return String.fromCodePoint(
    ...field.split(" ").map((hex) => parseInt(hex, 16)),
  );
}

/** Rows `[from, to, …rest]` sorted, with touching rows of equal rest joined. */
function joinRanges(rows: number[][]): number[] {
  const out: number[][] = [];
  for (const row of rows.toSorted((a, b) => a[0]! - b[0]!)) {
    const last = out.at(-1);
    if (
      last &&
      last[1]! + 1 === row[0] &&
      last.slice(2).join() === row.slice(2).join()
    )
      last[1] = row[1]!;
    else out.push([...row]);
  }
  return out.flat();
}

function propertyRanges(text: string, value: string): number[] {
  return joinRanges(
    dataLines(text)
      .filter((fields) => fields[1] === value)
      .map((fields) => codeRange(fields[0]!)),
  );
}

function literal(value: number | string): string {
  if (typeof value === "number") return String(value);
  return JSON.stringify(value).replace(
    /[\u007f-\uffff]/g,
    (unit) => `\\u${unit.charCodeAt(0).toString(16).padStart(4, "0")}`,
  );
}

function table(
  name: string,
  type: string,
  values: readonly (number | string)[],
): string {
  const lines: string[] = [];
  for (let i = 0; i < values.length; i += PER_LINE)
    lines.push(
      `  ${values
        .slice(i, i + PER_LINE)
        .map(literal)
        .join(", ")},`,
    );
  return `\nexport const ${name}: ${type} = [\n${lines.join("\n")}\n];\n`;
}

/** The text of `unicode.generated.ts`, from the vendored files `read` returns by name. */
export function generateUnicodeTables(read: (name: string) => string): string {
  const gcb = dataLines(read("GraphemeBreakProperty.txt")).map((fields) => {
    const cls = GCB_CLASSES.findIndex((name) => name === fields[1]);
    if (cls < 0)
      throw new RangeError(`unknown grapheme break value ${fields[1]}`);
    return [...codeRange(fields[0]!), cls + 1];
  });
  const emoji = read("emoji-data.txt");
  const wide = dataLines(read("EastAsianWidth.txt"))
    .filter((fields) => fields[1] === "W" || fields[1] === "F")
    .map((fields) => codeRange(fields[0]!));
  const upperSimple = dataLines(read("UnicodeData.txt"))
    .filter((fields) => fields[12] !== "")
    .flatMap((fields) => [parseInt(fields[0]!, 16), parseInt(fields[12]!, 16)]);
  const upperSpecial = dataLines(read("SpecialCasing.txt"))
    .filter((fields) => fields[4] === "")
    .map((fields): [number, string] => [
      parseInt(fields[0]!, 16),
      codePoints(fields[3]!),
    ])
    .toSorted((a, b) => a[0] - b[0])
    .flat();
  return (
    HEADER +
    table("GCB_RANGES", "readonly number[]", joinRanges(gcb)) +
    table(
      "EXT_PICT_RANGES",
      "readonly number[]",
      propertyRanges(emoji, "Extended_Pictographic"),
    ) +
    table(
      "EMOJI_PRESENTATION_RANGES",
      "readonly number[]",
      propertyRanges(emoji, "Emoji_Presentation"),
    ) +
    table("WIDE_RANGES", "readonly number[]", joinRanges(wide)) +
    table("UPPER_SIMPLE", "readonly number[]", upperSimple) +
    table("UPPER_SPECIAL", "readonly (number | string)[]", upperSpecial)
  );
}

// U+FFFF and the other noncharacters sit in a font's character map as sentinels, not as characters.
function isCharacter(codePoint: number): boolean {
  return (
    codePoint >= 0x20 &&
    (codePoint & 0xfffe) !== 0xfffe &&
    (codePoint < 0xfdd0 || codePoint > 0xfdef)
  );
}

/** The code points every face of `subset` holds; throws when a face's characters are not measured as `FONT_METRICS` says. */
function subsetCharacters(
  subset: "latin" | "latin-ext",
  read: (key: FontFaceKey) => Uint8Array,
): number[] {
  const faces = FONT_FACE_KEYS.filter(
    (key) => key.replace(/-\d+-\w+$/, "") === subset,
  ).map((key) => {
    const font = create(Buffer.from(read(key)));
    if (!("characterSet" in font))
      throw new TypeError(`${key} is a font collection`);
    if (
      font.unitsPerEm !== FONT_METRICS.unitsPerEm ||
      font.ascent !== FONT_METRICS.ascent ||
      font.descent !== FONT_METRICS.descent ||
      font.characterSet.some(
        (cp) =>
          font.glyphForCodePoint(cp).advanceWidth !== FONT_METRICS.advance,
      )
    )
      throw new RangeError(`${key} is not measured as FONT_METRICS says`);
    return new Set(font.characterSet);
  });
  return [...faces[0]!].filter(
    (cp) => isCharacter(cp) && faces.every((face) => face.has(cp)),
  );
}

/** The text of `font.generated.ts`, from the `.woff` file of each face `read` returns. */
export function generateFontTable(
  read: (key: FontFaceKey) => Uint8Array,
): string {
  const latin = subsetCharacters("latin", read);
  const inLatin = new Set(latin);
  const ext = subsetCharacters("latin-ext", read).filter(
    (cp) => !inLatin.has(cp),
  );
  return (
    HEADER +
    table(
      "FONT_LATIN",
      "readonly number[]",
      joinRanges(latin.map((cp) => [cp, cp])),
    ) +
    table(
      "FONT_LATIN_EXT",
      "readonly number[]",
      joinRanges(ext.map((cp) => [cp, cp])),
    )
  );
}

const commonOf = (sets: Set<number>[]): number[] =>
  [...sets[0]!]
    .filter((cp) => sets.every((s) => s.has(cp)))
    .toSorted((a, b) => a - b);

/** Generates `v3/tables/serif.generated.ts` with exact per-face FUnit advance widths for Source Serif 4. */
export function generateSerifTable(
  read: (key: FontFaceKey) => Uint8Array,
): string {
  const styles = [
    ["400-normal", "SERIF_ADVANCE_400"],
    ["400-italic", "SERIF_ADVANCE_400_I"],
    ["700-normal", "SERIF_ADVANCE_700"],
    ["700-italic", "SERIF_ADVANCE_700_I"],
  ] as const;
  let unitsPerEm = 0;
  let ascent = 0;
  let descent = 0;
  const subsets: Record<"latin" | "latin-ext", Set<number>[]> = {
    latin: [],
    "latin-ext": [],
  };
  const perStyle = new Map<string, Map<number, number>>();
  for (const [styleKey] of styles) perStyle.set(styleKey, new Map());

  for (const subset of ["latin", "latin-ext"] as const) {
    for (const [styleKey] of styles) {
      const key = `${subset}-${styleKey}` as FontFaceKey;
      const font = create(Buffer.from(read(key)));
      if (!("characterSet" in font))
        throw new TypeError(`${key} is a font collection`);
      if (unitsPerEm === 0) {
        unitsPerEm = font.unitsPerEm;
        ascent = font.ascent;
        descent = font.descent;
      } else if (
        font.unitsPerEm !== unitsPerEm ||
        font.ascent !== ascent ||
        font.descent !== descent
      ) {
        throw new RangeError(`${key} metrics differ from base serif face`);
      }
      const chars = new Set<number>();
      const map = perStyle.get(styleKey)!;
      for (const cp of font.characterSet) {
        if (!isCharacter(cp)) continue;
        let advance: number;
        try {
          advance = font.glyphForCodePoint(cp).advanceWidth;
        } catch {
          // Skip empty-contour whitespace glyphs (e.g. U+2002/2009/200B) that trip fontkit's _getCBox.
          continue;
        }
        chars.add(cp);
        if (!map.has(cp)) map.set(cp, advance);
      }
      subsets[subset].push(chars);
    }
  }

  const latin = commonOf(subsets.latin);
  const inLatin = new Set(latin);
  const ext = commonOf(subsets["latin-ext"]).filter((cp) => !inLatin.has(cp));
  const all = [...latin, ...ext].toSorted((a, b) => a - b);

  let out =
    HEADER +
    `\nexport const SERIF_METRICS = Object.freeze({\n  unitsPerEm: ${unitsPerEm},\n  ascent: ${ascent},\n  descent: ${descent},\n});\n` +
    table(
      "SERIF_LATIN",
      "readonly number[]",
      joinRanges(latin.map((cp) => [cp, cp])),
    ) +
    table(
      "SERIF_LATIN_EXT",
      "readonly number[]",
      joinRanges(ext.map((cp) => [cp, cp])),
    );

  for (const [styleKey, constName] of styles) {
    const map = perStyle.get(styleKey)!;
    const pairs: number[] = [];
    for (const cp of all)
      pairs.push(cp, map.get(cp) ?? Math.round(unitsPerEm * 0.5));
    out += table(constName, "readonly number[]", pairs);
  }
  return out;
}

const repoRoot = join(import.meta.dir, "..", "..");

function readUcd(name: string): string {
  return readFileSync(join(repoRoot, UCD_DIR, name), "utf8");
}

function readFace(key: FontFaceKey): Uint8Array {
  return readFileSync(
    Bun.resolveSync(
      `@fontsource/courier-prime/files/courier-prime-${key}.woff`,
      import.meta.dir,
    ),
  );
}

function readSerifFace(key: FontFaceKey): Uint8Array {
  return readFileSync(
    Bun.resolveSync(
      `@fontsource/source-serif-4/files/source-serif-4-${key}.woff`,
      import.meta.dir,
    ),
  );
}

if (import.meta.main) {
  const files = [
    [`${TABLES}/unicode.generated.ts`, generateUnicodeTables(readUcd)],
    [`${TABLES}/font.generated.ts`, generateFontTable(readFace)],
    [`${V3_TABLES}/serif.generated.ts`, generateSerifTable(readSerifFace)],
  ] as const;
  const check = process.argv.includes("--check");
  for (const [file, text] of files) {
    if (!check) await Bun.write(join(repoRoot, file), text);
    else if (readFileSync(join(repoRoot, file), "utf8") !== text) {
      console.log(`tables: ${file} is stale`);
      process.exit(1);
    }
  }
  if (check) console.log("tables: up to date");
}
